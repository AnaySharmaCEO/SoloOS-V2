// ============================================
// SIGN UP
// ============================================

export async function signUp(email: string, password: string): Promise<ApiResponse<AuthSession>> {
  try {
    const { data, error } = await supabase.auth.signUp({
      email,
      password,
      options: {
        emailRedirectTo: `${window.location.origin}/onboarding`,
      },
    });

    if (error) {
      // Security fallback: map backend trigger rejection to clean user-facing message
      if (isBackendDomainRejection(error.message)) {
        return { data: null, error: { message: UNTRUSTED_DOMAIN_MESSAGE } };
      }
      return { data: null, error: { message: error.message } };
    }

    if (!data.user) {
      return { data: null, error: { message: 'Sign up failed' } };
    }



    // Create mock Profile with defunct fields to keep frontend compile-safe and fully backward-compatible
    const newProfile: Profile = {
      id: '', // Will be generated by Supabase
      user_id: data.user.id,
      role: undefined,
      business_stage: undefined,
      blocker: undefined,
      avg_project_value: undefined,
      onboarding_complete: false,
      follow_up_interval: 3,
      risk_threshold: 5,
      notifications_follow_up: true,
      notifications_proposal: true,
      notifications_lead: true,
      notifications_weekly: false,
      full_name: '',
      notify_followup_reminders: true,
      notify_proposal_updates: true,
      notify_lead_activity: true,
      notify_weekly_digest: false,
      default_followup_interval_days: 3,
      risk_alert_threshold_days: 5,
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
    };

    // Database-compatible profile structure (only contains valid schema columns)
    const dbProfile = {
      user_id: data.user.id,
      onboarding_complete: false,
      full_name: '',
      notify_followup_reminders: true,
      notify_proposal_updates: true,
      notify_lead_activity: true,
      notify_weekly_digest: false,
      default_followup_interval_days: 3,
      risk_alert_threshold_days: 5,
      created_at: newProfile.created_at,
      updated_at: newProfile.updated_at,
    };

    // Don't use .select() after INSERT to avoid RLS re-evaluation issues
    // Do NOT fail signup if profile creation fails, since auth account is successfully created and email dispatched.
    const { error: profileError } = await supabase
      .from('profiles')
      .upsert(dbProfile, { onConflict: 'user_id' });

    if (profileError) {
      console.warn('[AUTH] Profile insertion skipped or failed during signUp (handled gracefully):', profileError);
    }

    // Seed default message templates
    try {
      await seedTemplates(data.user.id);
    } catch (templateError) {
      console.warn('[AUTH] Template seeding failed during signUp (handled gracefully):', templateError);
    }

    return {
      data: {
        user: data.user as User,
        profile: newProfile as Profile,
        access_token: data.session?.access_token,
        refresh_token: data.session?.refresh_token,
      },
      error: null,
    };
  } catch (error: any) {
    return { data: null, error: { message: error.message } };
  }
}

// ============================================
// SIGN IN
// ============================================

export async function signIn(email: string, password: string): Promise<ApiResponse<AuthSession>> {
  try {
    const { data, error } = await supabase.auth.signInWithPassword({
      email,
      password,
    });

    if (error) {
      return { data: null, error: { message: error.message } };
    }

    if (!data.user) {
      return { data: null, error: { message: 'Sign in failed' } };
    }



    // Get user profile
    const profileResult = await getProfile(data.user.id);

    if (profileResult.error) {
      return { data: null, error: profileResult.error };
    }

    return {
      data: {
        user: data.user as User,
        profile: profileResult.data!,
        access_token: data.session?.access_token,
        refresh_token: data.session?.refresh_token,
      },
      error: null,
    };
  } catch (error: any) {
    return { data: null, error: { message: error.message } };
  }
}

