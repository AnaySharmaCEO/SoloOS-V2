export async function getProfile(userId: string): Promise<ApiResponse<Profile>> {
  try {
    // Query without .select() first to avoid RLS issues
    const { data, error } = await supabase
      .from('profiles')
      .select('*')
      .eq('user_id', userId)
      .maybeSingle();

    if (error) {
      console.warn('Profile fetch error:', error);
      // Return a default profile instead of erroring out
      return {
        data: {
          id: '',
          user_id: userId,
          role: null,
          business_stage: null,
          blocker: null,
          avg_project_value: null,
          onboarding_complete: false,
          follow_up_interval: 3,
          risk_threshold: 5,
          notifications_follow_up: true,
          notifications_proposal: true,
          notifications_lead: true,
          notifications_weekly: false,
          full_name: '',
          notify_followup_reminders: true,
          notify_proposal_updates: true,
          notify_lead_activity: true,
          notify_weekly_digest: false,
          default_followup_interval_days: 3,
          risk_alert_threshold_days: 5,
          created_at: new Date().toISOString(),
          updated_at: new Date().toISOString(),
        },
        error: null,
      };
    }

    // If profile doesn't exist, auto-create it
    if (!data) {
      const newProfile: Profile = {
        id: '',
        user_id: userId,
        role: undefined,
        business_stage: undefined,
        blocker: undefined,
        avg_project_value: undefined,
        onboarding_complete: false,
        follow_up_interval: 3,
        risk_threshold: 5,
        notifications_follow_up: true,
        notifications_proposal: true,
        notifications_lead: true,
        notifications_weekly: false,
        full_name: '',
        notify_followup_reminders: true,
        notify_proposal_updates: true,
        notify_lead_activity: true,
        notify_weekly_digest: false,
        default_followup_interval_days: 3,
        risk_alert_threshold_days: 5,
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      };

      const dbProfile = {
        user_id: userId,
        onboarding_complete: false,
        full_name: '',
        notify_followup_reminders: true,
        notify_proposal_updates: true,
        notify_lead_activity: true,
        notify_weekly_digest: false,
        default_followup_interval_days: 3,
        risk_alert_threshold_days: 5,
        created_at: newProfile.created_at,
        updated_at: newProfile.updated_at,
      };

      const { data: createdProfile, error: createError } = await supabase
        .from('profiles')
        .upsert(dbProfile, { onConflict: 'user_id' })
        .select()
        .maybeSingle();

      if (createError) {
        console.warn('Failed to auto-create profile:', createError);
        // Return the default profile object even if insert fails
        return { data: newProfile as Profile, error: null };
      }

      // Seed templates if we just auto-created the profile
      try {
        await seedTemplates(userId);
      } catch (templateError) {
        console.warn('Template seeding failed in getProfile (handled gracefully):', templateError);
      }

      return {
        data: {
          ...newProfile,
          ...(createdProfile || {}),
        } as Profile,
        error: null,
      };
    }

    return { data: data as Profile, error: null };
  } catch (error: any) {
    console.warn('Profile fetch exception:', error);
    // Return default profile instead of failing
    return {
      data: {
        id: '',
        user_id: userId,
        role: null,
        business_stage: null,
        blocker: null,
        avg_project_value: null,
        onboarding_complete: false,
        follow_up_interval: 3,
        risk_threshold: 5,
        notifications_follow_up: true,
        notifications_proposal: true,
        notifications_lead: true,
        notifications_weekly: false,
        full_name: '',
        notify_followup_reminders: true,
        notify_proposal_updates: true,
        notify_lead_activity: true,
        notify_weekly_digest: false,
        default_followup_interval_days: 3,
        risk_alert_threshold_days: 5,
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      },
      error: null,
    };
  }
}

export async function updateProfile(userId: string, updates: Partial<Profile>): Promise<ApiResponse<Profile>> {
  try {
    const validDbKeys = [
      'role',
      'business_stage',
      'blocker',
      'avg_project_value',
      'onboarding_complete',
      'full_name',
      'notify_followup_reminders',
      'notify_proposal_updates',
      'notify_lead_activity',
      'notify_weekly_digest',
      'default_followup_interval_days',
      'risk_alert_threshold_days'
    ];

    const cleanUpdates: any = {};
    for (const key of Object.keys(updates)) {
      if (validDbKeys.includes(key)) {
        cleanUpdates[key] = (updates as any)[key];
      }
    }

    const updatesWithTimestamp = {
      ...cleanUpdates,
      updated_at: new Date().toISOString(),
    };

    // Don't use .select() after UPDATE due to RLS re-evaluation issues
    // Just perform the update and return the constructed profile
    const { error } = await supabase
      .from('profiles')
      .update(updatesWithTimestamp)
      .eq('user_id', userId);

    if (error) {
      return { data: null, error: { message: error.message } };
    }

    // First, try to get the full profile to ensure all fields are present
    const { data: fullProfile, error: fetchError } = await supabase
      .from('profiles')
      .select('*')
      .eq('user_id', userId)
      .maybeSingle();

    if (!fetchError && fullProfile) {
      return { data: fullProfile as Profile, error: null };
    }

    // If fetch fails due to RLS timing, construct profile from updates
    // This happens because RLS re-evaluates on SELECT after UPDATE
    // We trust the UPDATE succeeded if no error was returned
    console.warn('Profile fetch after update returned empty due to RLS timing, using partial profile');
    
    return {
      data: {
        id: '',
        user_id: userId,
        ...updatesWithTimestamp,
      } as Profile,
      error: null,
    };
  } catch (error: any) {
    return { data: null, error: { message: error.message } };
  }
}

export async function completeOnboarding(
  userId: string,
  onboardingData: {
    full_name?: string;
    role?: string;
    business_stage?: string;
    blocker?: string;
    avg_project_value?: number;
  }
): Promise<ApiResponse<Profile>> {
  return updateProfile(userId, {
    ...onboardingData,
    onboarding_complete: true,
  });
}

