// ============================================
// VERIFY CURRENT PASSWORD
// ============================================

export async function verifyCurrentPassword(email: string, currentPassword: string): Promise<ApiResponse<boolean>> {
  try {
    const { error } = await supabase.auth.signInWithPassword({
      email,
      password: currentPassword,
    });
    if (error) {
      return { data: false, error: { message: 'Incorrect current password. Please try again.' } };
    }
    return { data: true, error: null };
  } catch (error: any) {
    return { data: false, error: { message: error.message || 'Verification failed.' } };
  }
}

